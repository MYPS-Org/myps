SET NOCOUNT ON;
SET QUOTED_IDENTIFIER ON;
DECLARE @S SYSNAME = '$SCHEMA$', @T SYSNAME = '$TABLE$';
DECLARE @oid INT = OBJECT_ID(QUOTENAME(@S)+'.'+QUOTENAME(@T));
DECLARE @nl CHAR(2) = CHAR(13)+CHAR(10);
DECLARE @dbcoll SYSNAME = CONVERT(SYSNAME, DATABASEPROPERTYEX(DB_NAME(),'Collation'));
DECLARE @o NVARCHAR(MAX) = N'';
DECLARE @sep NVARCHAR(10) = N',' + CHAR(13)+CHAR(10);
DECLARE @full NVARCHAR(300) = QUOTENAME(@S)+'.'+QUOTENAME(@T);

IF @oid IS NULL BEGIN PRINT '-- table not found'; RETURN; END

/* ---------- header ---------- */
SET @o = N'/* Auto-generated from ' + DB_NAME() COLLATE DATABASE_DEFAULT
       + N'. DO NOT EDIT - regenerated by GenerateTables.ps1 on build. */' + @nl
       + N'-- Required for filtered indexes; sqlcmd defaults QUOTED_IDENTIFIER OFF.' + @nl
       + N'SET QUOTED_IDENTIFIER ON;' + @nl
       + N'SET ANSI_NULLS ON;' + @nl
       + N'GO' + @nl
       + N'IF OBJECT_ID(N''' + @full + N''', N''U'') IS NULL' + @nl + N'BEGIN' + @nl
       + N'CREATE TABLE ' + @full + N' (' + @nl;

/* ---------- columns ---------- */
DECLARE @cols NVARCHAR(MAX);
SELECT @cols = STRING_AGG(CAST(x.line AS NVARCHAR(MAX)), @sep) WITHIN GROUP (ORDER BY x.column_id)
FROM (
  SELECT c.column_id,
    N'    ' + QUOTENAME(c.name) COLLATE DATABASE_DEFAULT + N' '
    + UPPER(ty.name COLLATE DATABASE_DEFAULT)
    + CASE
        WHEN ty.name IN ('varchar','char','varbinary','binary')
          THEN N'(' + CASE WHEN c.max_length = -1 THEN N'MAX' ELSE CAST(c.max_length AS NVARCHAR(10)) END + N')'
        WHEN ty.name IN ('nvarchar','nchar')
          THEN N'(' + CASE WHEN c.max_length = -1 THEN N'MAX' ELSE CAST(c.max_length/2 AS NVARCHAR(10)) END + N')'
        WHEN ty.name IN ('decimal','numeric')
          THEN N'(' + CAST(c.precision AS NVARCHAR(10)) + N',' + CAST(c.scale AS NVARCHAR(10)) + N')'
        WHEN ty.name IN ('datetime2','time','datetimeoffset')
          THEN CASE WHEN c.scale <> 7 THEN N'(' + CAST(c.scale AS NVARCHAR(10)) + N')' ELSE N'' END
        ELSE N'' END
    + CASE WHEN c.collation_name IS NOT NULL AND c.collation_name <> @dbcoll
           THEN N' COLLATE ' + c.collation_name COLLATE DATABASE_DEFAULT ELSE N'' END
    /* Always IDENTITY(1,1) regardless of the live seed/increment: these files
       track SCHEMA shape for git diffs, not current data state. Emitting the
       real seed would make every sync show a diff as rows are inserted, even
       when nothing about the table's structure changed. */
    + CASE WHEN c.is_identity = 1 THEN N' IDENTITY(1,1)' ELSE N'' END
    + CASE WHEN cc.definition IS NOT NULL THEN N' AS ' + cc.definition COLLATE DATABASE_DEFAULT ELSE N'' END
    + CASE WHEN cc.definition IS NOT NULL THEN N''
           WHEN c.is_nullable = 1 THEN N' NULL' ELSE N' NOT NULL' END
    + CASE WHEN dc.name IS NOT NULL
           THEN N' CONSTRAINT ' + QUOTENAME(dc.name) COLLATE DATABASE_DEFAULT
                + N' DEFAULT ' + dc.definition COLLATE DATABASE_DEFAULT ELSE N'' END AS line
  FROM sys.columns c
  JOIN sys.types ty ON ty.user_type_id = c.user_type_id
  LEFT JOIN sys.default_constraints dc ON dc.parent_object_id = c.object_id AND dc.parent_column_id = c.column_id
  LEFT JOIN sys.computed_columns cc ON cc.object_id = c.object_id AND cc.column_id = c.column_id
  WHERE c.object_id = @oid
) AS x;
SET @o = @o + ISNULL(@cols, N'');

/* ---------- PK + UNIQUE constraints ---------- */
DECLARE @keys NVARCHAR(MAX);
SELECT @keys = STRING_AGG(CAST(k.line AS NVARCHAR(MAX)), @sep) WITHIN GROUP (ORDER BY k.ord, k.nm)
FROM (
  SELECT CASE kc.type WHEN 'PK' THEN 0 ELSE 1 END AS ord, kc.name COLLATE DATABASE_DEFAULT AS nm,
    N'    CONSTRAINT ' + QUOTENAME(kc.name) COLLATE DATABASE_DEFAULT + N' '
    + CASE kc.type WHEN 'PK' THEN N'PRIMARY KEY' ELSE N'UNIQUE' END
    + CASE WHEN i.type = 1 THEN N' CLUSTERED' ELSE N' NONCLUSTERED' END
    + N' (' + STUFF((SELECT N', ' + QUOTENAME(c2.name) COLLATE DATABASE_DEFAULT
                          + CASE WHEN ic.is_descending_key = 1 THEN N' DESC' ELSE N' ASC' END
                     FROM sys.index_columns ic
                     JOIN sys.columns c2 ON c2.object_id = ic.object_id AND c2.column_id = ic.column_id
                     WHERE ic.object_id = kc.parent_object_id AND ic.index_id = kc.unique_index_id
                       AND ic.is_included_column = 0
                     ORDER BY ic.key_ordinal FOR XML PATH(''), TYPE).value('.','NVARCHAR(MAX)'),1,2,N'')
    + N')' AS line
  FROM sys.key_constraints kc
  JOIN sys.indexes i ON i.object_id = kc.parent_object_id AND i.index_id = kc.unique_index_id
  WHERE kc.parent_object_id = @oid
) AS k;

/* ---------- CHECK constraints ---------- */
DECLARE @chk NVARCHAR(MAX);
SELECT @chk = STRING_AGG(CAST(z.line AS NVARCHAR(MAX)), @sep) WITHIN GROUP (ORDER BY z.nm)
FROM (
  SELECT ck.name COLLATE DATABASE_DEFAULT AS nm,
    N'    CONSTRAINT ' + QUOTENAME(ck.name) COLLATE DATABASE_DEFAULT
    + N' CHECK ' + ck.definition COLLATE DATABASE_DEFAULT AS line
  FROM sys.check_constraints ck WHERE ck.parent_object_id = @oid
) AS z;

/* stitch column / key / check sections with correct commas */
IF @keys IS NOT NULL SET @o = @o + N',' + @nl + @keys;
IF @chk  IS NOT NULL SET @o = @o + N',' + @nl + @chk;
SET @o = @o + @nl + N');' + @nl + N'END' + @nl;

/* ---------- FOREIGN KEYS (after table so order never breaks deps) ---------- */
DECLARE @fk NVARCHAR(MAX);
SELECT @fk = STRING_AGG(CAST(f.line AS NVARCHAR(MAX)), N'') WITHIN GROUP (ORDER BY f.nm)
FROM (
  SELECT fk.name COLLATE DATABASE_DEFAULT AS nm, @nl
  + N'IF NOT EXISTS (SELECT 1 FROM sys.foreign_keys WHERE name = N'''
  + fk.name COLLATE DATABASE_DEFAULT + N''' AND parent_object_id = OBJECT_ID(N''' + @full + N'''))' + @nl
  + N'ALTER TABLE ' + @full + N' ADD CONSTRAINT ' + QUOTENAME(fk.name) COLLATE DATABASE_DEFAULT
  + N' FOREIGN KEY ('
  + STUFF((SELECT N', ' + QUOTENAME(pc.name) COLLATE DATABASE_DEFAULT
           FROM sys.foreign_key_columns fkc
           JOIN sys.columns pc ON pc.object_id = fkc.parent_object_id AND pc.column_id = fkc.parent_column_id
           WHERE fkc.constraint_object_id = fk.object_id
           ORDER BY fkc.constraint_column_id FOR XML PATH(''), TYPE).value('.','NVARCHAR(MAX)'),1,2,N'')
  + N') REFERENCES ' + QUOTENAME(SCHEMA_NAME(rt.schema_id)) COLLATE DATABASE_DEFAULT
  + N'.' + QUOTENAME(rt.name) COLLATE DATABASE_DEFAULT + N' ('
  + STUFF((SELECT N', ' + QUOTENAME(rc.name) COLLATE DATABASE_DEFAULT
           FROM sys.foreign_key_columns fkc
           JOIN sys.columns rc ON rc.object_id = fkc.referenced_object_id AND rc.column_id = fkc.referenced_column_id
           WHERE fkc.constraint_object_id = fk.object_id
           ORDER BY fkc.constraint_column_id FOR XML PATH(''), TYPE).value('.','NVARCHAR(MAX)'),1,2,N'')
  + N')'
  + CASE fk.delete_referential_action WHEN 1 THEN N' ON DELETE CASCADE'
         WHEN 2 THEN N' ON DELETE SET NULL' WHEN 3 THEN N' ON DELETE SET DEFAULT' ELSE N'' END
  + CASE fk.update_referential_action WHEN 1 THEN N' ON UPDATE CASCADE'
         WHEN 2 THEN N' ON UPDATE SET NULL' WHEN 3 THEN N' ON UPDATE SET DEFAULT' ELSE N'' END
  + N';' + @nl AS line
  FROM sys.foreign_keys fk
  JOIN sys.tables rt ON rt.object_id = fk.referenced_object_id
  WHERE fk.parent_object_id = @oid
) AS f;
SET @o = @o + ISNULL(@fk, N'');

/* ---------- INDEXES (skip PK/UQ constraint-backed) ---------- */
DECLARE @ix NVARCHAR(MAX);
SELECT @ix = STRING_AGG(CAST(g.line AS NVARCHAR(MAX)), N'') WITHIN GROUP (ORDER BY g.nm)
FROM (
  SELECT i.name COLLATE DATABASE_DEFAULT AS nm, @nl
  + N'IF NOT EXISTS (SELECT 1 FROM sys.indexes WHERE name = N''' + i.name COLLATE DATABASE_DEFAULT
  + N''' AND object_id = OBJECT_ID(N''' + @full + N'''))' + @nl
  + N'CREATE ' + CASE WHEN i.is_unique = 1 THEN N'UNIQUE ' ELSE N'' END
  + CASE WHEN i.type = 1 THEN N'CLUSTERED ' ELSE N'NONCLUSTERED ' END
  + N'INDEX ' + QUOTENAME(i.name) COLLATE DATABASE_DEFAULT + N' ON ' + @full + N' ('
  + STUFF((SELECT N', ' + QUOTENAME(c3.name) COLLATE DATABASE_DEFAULT
                + CASE WHEN ic.is_descending_key = 1 THEN N' DESC' ELSE N' ASC' END
           FROM sys.index_columns ic
           JOIN sys.columns c3 ON c3.object_id = ic.object_id AND c3.column_id = ic.column_id
           WHERE ic.object_id = i.object_id AND ic.index_id = i.index_id AND ic.is_included_column = 0
           ORDER BY ic.key_ordinal FOR XML PATH(''), TYPE).value('.','NVARCHAR(MAX)'),1,2,N'')
  + N')'
  + ISNULL(N' INCLUDE (' + STUFF((SELECT N', ' + QUOTENAME(c4.name) COLLATE DATABASE_DEFAULT
           FROM sys.index_columns ic
           JOIN sys.columns c4 ON c4.object_id = ic.object_id AND c4.column_id = ic.column_id
           WHERE ic.object_id = i.object_id AND ic.index_id = i.index_id AND ic.is_included_column = 1
           ORDER BY ic.index_column_id FOR XML PATH(''), TYPE).value('.','NVARCHAR(MAX)'),1,2,N'') + N')', N'')
  + CASE WHEN i.has_filter = 1 THEN N' WHERE ' + i.filter_definition COLLATE DATABASE_DEFAULT ELSE N'' END
  + N';' + @nl AS line
  FROM sys.indexes i
  WHERE i.object_id = @oid AND i.type > 0 AND i.is_primary_key = 0 AND i.is_unique_constraint = 0
) AS g;
SET @o = @o + ISNULL(@ix, N'');

/* ---------- emit in chunks (PRINT caps at 4000 nchars) ---------- */
DECLARE @i INT = 1, @len INT = LEN(@o), @chunk NVARCHAR(MAX), @brk INT;
WHILE @i <= @len
BEGIN
    SET @chunk = SUBSTRING(@o, @i, 3500);
    SET @brk = LEN(@chunk) - CHARINDEX(CHAR(10), REVERSE(@chunk)) + 1;
    IF @i + 3500 <= @len AND @brk > 1 SET @chunk = LEFT(@chunk, @brk);
    PRINT @chunk;
    SET @i = @i + LEN(@chunk);
END
