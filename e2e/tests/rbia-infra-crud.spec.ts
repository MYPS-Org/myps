// =============================================================================
// rbia-infra-crud.spec.ts — Infra Management: Roads -> Road Sections -> Bridges,
// add / edit / delete through the UI, in the order QA runs S06.
//
// What it guards (all were broken on main, 2026-10-20):
//   - Road / Road Section edit: the BE duplicate check had no name/ID comparison,
//     so every edit failed once a second row existed (S06-TC003-P002, TC008-P001).
//   - Add Section / Add Bridge from a row AFTER an edit: the dialogs treated any
//     shared selection as Edit mode and posted an edit with Id 0 (TC005, TC010).
//   - Lists did not refresh after add/edit (rows only showed after a reload).
//   - Road Sections list: Length / Engineering District were blank, because the
//     BE returns LengthM / DEOParticipantId (TC006-P001), and Edit stopped at
//     "Please enter the length".
//   - Delete: rows added in the UI were saved with NetworkStatusId 0 and refused
//     as "migrated from RBIA"; bridge delete called a route that does not exist
//     (TC004, TC009, TC014).
//   - Filter: Classification was ignored by the BE (TC002-P004), and offered a
//     "Quaternary" the classification table does not have.
//   - Road / Section / Bridge IDs were typed by hand; the API now generates them
//     (road: from the island picked; section / bridge: the parent's island code)
//     (TC003-P001, TC005, TC010).
//   - Column headers looked sortable but the sort never reached the server
//     (TC001-P001): the second test checks the whole list is re-ordered.
//   - RBIA rows offered Edit / Delete (TC008, TC013): they are view-only now.
//
// DATA: creates one FR road, FS section and FB bridge (generated IDs, read
// from the success toasts) and deletes them again, in the UI and once more through the API in
// afterEach, so a failed run leaves nothing behind.
//
// PREREQUISITE — Vite must proxy to the LOCAL API:
//   cd FE && VITE_API_BASE_URL=http://localhost:5015 npx vite --port 8080 --strictPort
// =============================================================================

import { test, expect, type Page, type Locator } from '@playwright/test';
import { login } from './helpers/auth';

const n = String(90000 + (Date.now() % 9999)).padStart(5, '0');
/** Generated by the API on Add; read back from the success toasts. */
let ROAD_ID = '';
let SECTION_ID = '';
let BRIDGE_ID = '';
const ROAD_NAME = `e2e road ${n}`;
const ROAD_NAME_EDITED = `e2e road ${n} edited`;
const BRIDGE_NAME = `e2e bridge ${n}`;
const BRIDGE_NAME_EDITED = `e2e bridge ${n} edited`;

const dialog = (page: Page) => page.getByRole('dialog');
const row = (page: Page, text: string): Locator => page.locator('table tbody tr', { hasText: text });
/** Tab buttons carry their row count: "Road Sections 4455". */
const tab = (page: Page, name: string) => page.getByRole('button', { name: new RegExp(`^${name} \\d+$`) });
/** "Filter", or "Filter 2" once filters are active (badge with the active count). */
const filterButton = (page: Page) => page.getByRole('button', { name: /^Filter( \d+)?$/ });

async function confirmDelete(page: Page) {
  await dialog(page).getByPlaceholder('Type DELETE to confirm').fill('DELETE');
  await dialog(page).locator('button[type="submit"]').click();
}

test.describe('Infra Management — Roads, Road Sections, Bridges CRUD', () => {
  // In afterEach, not a finally: after a test timeout the test body's page requests no longer
  // go out, but hooks still get a live page (fixtures are torn down after them) and fresh time.
  test.afterEach(async ({ page }) => {
    // Children first: a road with sections, or a section with bridges, is refused.
    if (BRIDGE_ID) {
      await page.request.post('/api/FutureInfra/DeleteFutureBridg', { data: { BridgeId: BRIDGE_ID } }).catch(() => {});
    }
    if (SECTION_ID) {
      await page.request.post('/api/FutureInfra/DeleteFutureRoadSection', { data: { RoadSectionId: SECTION_ID } }).catch(() => {});
    }
    if (ROAD_ID) {
      await page.request.post('/api/FutureInfra/DeleteFutureRoad', { data: { RoadId: ROAD_ID } }).catch(() => {});
    }
  });

  test('add, edit, add-from-row, filter and delete through the UI', async ({ page }) => {
    await login(page);
    {
      await page.goto('/infrastructure-management');

      await test.step('TC001-P001 / TC008 / TC013 RBIA roads are view-only', async () => {
        const rbiaRow = page.locator('table tbody tr', { has: page.getByTitle(/Maintained in RBIA/) }).first();
        await expect(rbiaRow).toBeVisible();
        await expect(rbiaRow.getByTitle('Edit', { exact: true })).toHaveCount(0);
        await expect(rbiaRow.getByTitle('Delete', { exact: true })).toHaveCount(0);
        await expect(rbiaRow.getByRole('button', { name: 'Add Section' })).toBeVisible();
      });

      await test.step('TC003-P001 add a future road: the Road ID is generated, it shows without a reload', async () => {
        await page.getByRole('button', { name: 'Add Road' }).click();
        await expect(dialog(page).getByPlaceholder(/Enter Road ID/)).toHaveCount(0);
        await dialog(page).getByLabel('Island').selectOption('LZ');
        await dialog(page).getByPlaceholder('Enter road name').fill(ROAD_NAME);
        await dialog(page).locator('select').last().selectOption({ label: 'Primary' });
        await dialog(page).getByRole('button', { name: 'Create Road' }).click();
        const toast = page.getByText(/^Future road FR\d{5}LZ added\.$/);
        await expect(toast).toBeVisible();
        ROAD_ID = (await toast.textContent())!.match(/FR\d{5}LZ/)![0];
        await expect(row(page, ROAD_ID)).toContainText(ROAD_NAME);
      });

      await test.step('TC003-P002 edit the road (name + classification)', async () => {
        await row(page, ROAD_ID).locator('button').nth(0).click();
        await expect(dialog(page)).toContainText('Edit Future Road');
        await expect(dialog(page).locator('input[readonly]')).toHaveValue(ROAD_ID);
        await dialog(page).getByPlaceholder('Enter road name').fill(ROAD_NAME_EDITED);
        await dialog(page).locator('select').first().selectOption({ label: 'Secondary' });
        await dialog(page).getByRole('button', { name: 'Update Road' }).click();
        await expect(page.getByText('Future road updated.')).toBeVisible();
        await expect(row(page, ROAD_ID)).toContainText(ROAD_NAME_EDITED);
        await expect(row(page, ROAD_ID)).toContainText('Secondary');
      });

      await test.step('TC002-P004 filter by name + classification', async () => {
        await filterButton(page).click();
        await expect(dialog(page).locator('select option')).toHaveText(['All', 'Primary', 'Secondary', 'Tertiary']);
        await dialog(page).locator('input').nth(1).fill(ROAD_NAME_EDITED);
        await dialog(page).locator('select').selectOption('1'); // Primary: must NOT match the edited road
        await dialog(page).getByRole('button', { name: 'Apply Filter' }).click();
        await expect(row(page, ROAD_ID)).toHaveCount(0);
        await filterButton(page).click();
        await dialog(page).locator('select').selectOption('2'); // Secondary: matches
        await dialog(page).getByRole('button', { name: 'Apply Filter' }).click();
        await expect(row(page, ROAD_ID)).toHaveCount(1);
        await page.getByRole('button', { name: 'Clear Filter' }).click();
      });

      await test.step('TC005-P001 add a section from the road row, right after an edit', async () => {
        await row(page, ROAD_ID).getByRole('button', { name: 'Add Section' }).click();
        await expect(dialog(page)).toContainText(`Add Road Section for ${ROAD_ID}`);
        await expect(dialog(page).getByLabel('Section Road ID')).toHaveValue('FS·····LZ'); // generated, not typed
        await dialog(page).getByPlaceholder(/section length/).fill('120');
        await dialog(page).locator('select').last().selectOption({ index: 1 });
        await dialog(page).getByRole('button', { name: 'Create Road Section' }).click();
        const toast = page.getByText(/^Future road section FS\d{5}LZ added\.$/);
        await expect(toast).toBeVisible();
        SECTION_ID = (await toast.textContent())!.match(/FS\d{5}LZ/)![0];
      });

      await test.step('TC006-P001 the section list shows length and engineering district', async () => {
        await tab(page, 'Road Sections').click();
        const r = row(page, SECTION_ID);
        await expect(r).toContainText(ROAD_ID);
        await expect(r).toContainText('120 m');
        await expect(r).toContainText('District Engineering Office'); // DEO name, not the OI code
      });

      await test.step('TC008-P001 edit the section length', async () => {
        await row(page, SECTION_ID).locator('button').nth(0).click();
        await expect(dialog(page)).toContainText('Edit Future Road Section');
        await expect(dialog(page).getByLabel('Section Road ID')).toHaveValue(SECTION_ID);
        await expect(dialog(page).getByPlaceholder(/section length/)).toHaveValue('120');
        await dialog(page).getByPlaceholder(/section length/).fill('150');
        await dialog(page).getByRole('button', { name: 'Update Road Section' }).click();
        await expect(page.getByText('Future road section updated.')).toBeVisible();
        await expect(row(page, SECTION_ID)).toContainText('150 m');
      });

      await test.step('TC010-P001 add a bridge from the section row, right after an edit', async () => {
        await row(page, SECTION_ID).getByRole('button', { name: 'Add Bridge' }).click();
        await expect(dialog(page)).toContainText('Add New Future Bridge');
        await expect(dialog(page).getByLabel('Bridge ID')).toHaveValue('FB·····LZ');
        await dialog(page).getByPlaceholder('Enter bridge name').fill(BRIDGE_NAME);
        await dialog(page).getByPlaceholder(/starting chainage/).fill('0');
        await dialog(page).getByPlaceholder(/bridge length/).fill('25');
        await dialog(page).getByPlaceholder(/carriageway width/).fill('7');
        await dialog(page).getByRole('button', { name: 'Create Bridge' }).click();
        const toast = page.getByText(/^Future bridge FB\d{5}LZ added\.$/);
        await expect(toast).toBeVisible();
        BRIDGE_ID = (await toast.textContent())!.match(/FB\d{5}LZ/)![0];
      });

      await test.step('TC011-P001 / TC013-P001 the bridge is listed and can be edited', async () => {
        await tab(page, 'Bridges').click();
        await expect(row(page, BRIDGE_ID)).toContainText(BRIDGE_NAME);
        await row(page, BRIDGE_ID).locator('button').nth(0).click();
        await expect(dialog(page)).toContainText('Edit Future Bridge');
        await expect(dialog(page).getByLabel('Bridge ID')).toHaveValue(BRIDGE_ID);
        await dialog(page).getByPlaceholder('Enter bridge name').fill(BRIDGE_NAME_EDITED);
        await dialog(page).getByRole('button', { name: 'Update Bridge' }).click();
        await expect(page.getByText('Future bridge updated.')).toBeVisible();
        await expect(row(page, BRIDGE_ID)).toContainText(BRIDGE_NAME_EDITED);
      });

      await test.step('TC014-P001 / TC009-P001 / TC004-P001 delete bridge, section, road', async () => {
        await row(page, BRIDGE_ID).locator('button').nth(1).click();
        await confirmDelete(page);
        await expect(page.getByText('Bridge deleted successfully.')).toBeVisible();
        await expect(row(page, BRIDGE_ID)).toHaveCount(0);

        await tab(page, 'Road Sections').click();
        await row(page, SECTION_ID).locator('button').nth(1).click();
        await confirmDelete(page);
        await expect(page.getByText('Road section deleted successfully.')).toBeVisible();
        await expect(row(page, SECTION_ID)).toHaveCount(0);

        await tab(page, 'Roads').click();
        await row(page, ROAD_ID).locator('button').nth(1).click();
        await confirmDelete(page);
        await expect(row(page, ROAD_ID)).toHaveCount(0);
      });
    }
  });

  test('TC001-P001 column headers sort the whole list on the server, and paging keeps the order', async ({ page }) => {
    await login(page);
    await page.goto('/infrastructure-management');
    await expect(page.locator('table tbody tr').first()).toBeVisible();

    type Page1 = { lists: { Name: string }[]; page: number };
    const sortedFetch = (direction: 0 | 1, navigation?: number) =>
      page.waitForResponse((r) => {
        if (!r.url().includes('/ShowFutureRoads')) return false;
        const body = r.request().postDataJSON();
        return body?.sortField === 'Name' && body?.sortDirection === direction
          && (navigation === undefined || body?.Navigation === navigation);
      });
    const shownNames = async () =>
      (await page.locator('table tbody tr td:nth-child(2)').allTextContents()).map((t) => t.trim());
    const nameHeader = page.locator('th', { hasText: 'Road Name' });

    // Ascending: the request carries the sort, the table shows the server's order, the header an arrow.
    let response = sortedFetch(0);
    await nameHeader.click();
    const asc = (await (await response).json()) as Page1;
    await expect.poll(shownNames).toEqual(asc.lists.map((r) => r.Name));
    await expect(nameHeader.locator('svg')).toHaveCount(1);

    // Next keeps the order (row positions as cursors) and moves to genuinely different rows.
    response = sortedFetch(0, 2);
    await page.getByRole('button', { name: 'Next page' }).click();
    const asc2 = (await (await response).json()) as Page1;
    expect(asc2.page).toBe(2);
    expect(asc2.lists.map((r) => r.Name)).not.toEqual(asc.lists.map((r) => r.Name));
    await expect.poll(shownNames).toEqual(asc2.lists.map((r) => r.Name));

    // Second click: descending, back on page 1 (a new order drops the old cursors).
    response = sortedFetch(1);
    await nameHeader.click();
    const desc = (await (await response).json()) as Page1;
    expect(desc.page).toBe(1);
    expect(desc.lists[0].Name).not.toBe(asc.lists[0].Name);
    await expect.poll(shownNames).toEqual(desc.lists.map((r) => r.Name));
  });
});
